# 10. paired 95% intervals for the audit-score difference ΔJ (design-matched minus comparator), from the saved
#     per-replicate declarations in v2_eval_*.csv. Every procedure audits the same simulated counts in a replicate,
#     so the comparison is paired. The resampling unit is the simulated world, resampled within each
#     (world, keep) cell; B = 2000. This post-processes saved notebook outputs and fits no models.
def audit_J(Pm):
    acc = Pm.xs("homogeneous", level="world").groupby(level="keep").mean().mean()
    fts = Pm.drop("homogeneous", level="world").groupby(level=["world", "keep"]).mean().groupby(level="keep").mean().mean()
    return acc - fts


ci_rows = []
for st in ("TX", "CA"):
    f_ = RES / f"v2_eval_{st}.csv"
    if not f_.exists(): continue
    E = pd.read_csv(f_); E["r"] = E.groupby(["world", "keep", "procedure"]).cumcount()
    Pm = E.pivot_table(index=["world", "keep", "r"], columns="procedure", values="fair", aggfunc="first").astype(float)
    dm = next(p for p in Pm.columns if p.startswith("DESIGN")); s9 = next(p for p in Pm.columns if p.startswith("§9"))
    j0 = audit_J(Pm); est = j0.drop([dm, s9]); best = est.idxmax()
    comps = [(best, "best established"), (s9, "§9 calibration")]
    cells = [g for _, g in Pm.groupby(level=["world", "keep"])]; rng = np.random.default_rng(20261106); D = {c: [] for c, _ in comps}
    for _ in range(2000):
        jb = audit_J(pd.concat([g.iloc[rng.integers(0, len(g), len(g))] for g in cells]))
        for c, _ in comps: D[c].append(jb[dm] - jb[c])
    for c, role in comps:
        d = np.array(D[c]); ci_rows.append(dict(state=st, proposed=dm, comparator=c, role=role, dJ=j0[dm] - j0[c],
                                                lo95=np.percentile(d, 2.5), hi95=np.percentile(d, 97.5), B=2000))
if ci_rows:
    C = pd.DataFrame(ci_rows); C.round(4).to_csv(RES / "v2_paired_J_ci.csv", index=False)
