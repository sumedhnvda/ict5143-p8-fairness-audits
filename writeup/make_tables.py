def f(x, d=3):
    if pd.isna(x): return "--"
    x = 0.0 if round(x, d) == 0 else x                         # no "-0.000"
    return f"{x:.{d}f}".replace("-", "$-$")


def write(name, body):
    (TAB / f"{name}.tex").write_text("% generated by make_tables.py from ../results; do not edit by hand\n" + body)


def tex(s):
    return str(s).replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("·", r"$\cdot$")


